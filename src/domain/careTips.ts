function normalizePlantName(name: string): string {
  return name.trim();
}

export function getCareTips(name: string): string | null {
  const normalized = normalizePlantName(name);
  for (const [plantName, tips] of tipsMap) {
    if (normalized.includes(plantName)) {
      return tips;
    }
  }
  return null;
}
